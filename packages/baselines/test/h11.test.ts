describe("h11", () => {
  beforeAll(async () => {
    await loadH11();
  });
  for (const [t, e] of cases) it(`"${t}"`, () => expect(parseH11(t, TODAY)).toBe(e));

  it("every output parses and round-trips in core", () => {
    for (const [t] of cases) {
      const out = parseH11(t, TODAY);
      expect(serializeDsl(parseDsl(out)), t).toBe(out);
    }
  });

  it("resolves the new forms", () => {
    const o = { today: TODAY, weekStart: 0 as const };
    expect(resolveDsl(parseH11("easter", TODAY), o).start?.date).toBe("2027-03-28");
    expect(resolveDsl(parseH11("good friday", TODAY), o).start?.date).toBe("2027-03-26");
    expect(resolveDsl(parseH11("friday of next week", TODAY), o).start?.date).toBe("2026-11-13");
    expect(resolveDsl(parseH11("victoria day", TODAY), o).start?.date).toBe("2027-05-24");
    expect(resolveDsl(parseH11("black friday", TODAY), o).start?.date).toBe("2026-11-27");
  });

  it("uses the legacy weekday form when it gives the same day", () => {
    expect(parseH11("monday of next week", TODAY)).toBe("d mo+1");
    expect(parseH11("friday of next week", TODAY)).toBe("d fr@W+1");
    // 2026-11-06 is a Friday: the first Friday after today is the one next week
    expect(parseH11("friday of next week", "2026-11-06")).toBe("d fr+1");
  });

  it("is registered as an engine and falls back to h10 before loading", async () => {
    expect((await h11.predict("easter", undefined, { today: TODAY })).dsl).toBe("d E+0");
    expect(parseH10("easter", TODAY)).toBe("x");
  });
});
