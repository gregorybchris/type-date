"""Write packages/core/src/lunar-table.ts: dates of the lunar and lunisolar holidays, from the `holidays` package.

Run: uv run --script training/gen/lunar/make_tables.py

Sources (holidays 0.83 tables): Chinese calendar (Hong Kong Observatory data), India's Diwali and Holi
(2001-2035 only), Umm al-Qura for the Islamic dates (1925-2077), Hebrew calendar (computed). The Hebrew dates are
checked against convertdate's arithmetic calendar; a mismatch stops the script.
"""

from datetime import date
from pathlib import Path

from convertdate import hebrew
from holidays.calendars.chinese import _ChineseLunisolar as Chinese
from holidays.calendars.hebrew import _HebrewLunisolar as Hebrew
from holidays.calendars.hindu import _HinduLunisolar as Hindu
from holidays.calendars.islamic import _IslamicLunar as Islamic

FIRST, LAST = 2000, 2100
EPOCH = date(2000, 1, 1)
OUT = Path(__file__).resolve().parents[3] / "packages/core/src/lunar-table.ts"

SOURCES = {
    "lny": Chinese.LUNAR_NEW_YEAR_DATES,
    "midautumn": Chinese.MID_AUTUMN_DATES,
    "dragonboat": Chinese.DRAGON_BOAT_DATES,
    "diwali": Hindu.DIWALI_INDIA_DATES,
    "holi": Hindu.HOLI_DATES,
    "ramadan": Islamic.RAMADAN_BEGINNING_DATES,
    "eidfitr": Islamic.EID_AL_FITR_DATES,
    "eidadha": Islamic.EID_AL_ADHA_DATES,
    "roshhashanah": Hebrew.ROSH_HASHANAH_DATES,
    "yomkippur": Hebrew.YOM_KIPPUR_DATES,
    "passover": Hebrew.PASSOVER_DATES,
    "hanukkah": Hebrew.HANUKKAH_DATES,
    "purim": Hebrew.PURIM_DATES,
}

# Hebrew month and day of each Hebrew holiday, for the check (convertdate months: 1 Nisan ... 7 Tishri, 9 Kislev,
# 12 Adar, 13 Adar II).
HEBREW_CHECK = {"roshhashanah": (7, 1), "yomkippur": (7, 10), "passover": (1, 15), "hanukkah": (9, 25)}


def dates(table: dict) -> list[date]:
    out = []
    for y, v in table.items():
        if not FIRST <= y <= LAST:
            continue
        pairs = v if isinstance(v[0], tuple) else (v,)
        out += [date(y, m, d) for m, d in pairs]
    return sorted(out)


def check_hebrew(code: str, ds: list[date]) -> None:
    if code == "purim":
        for d in ds:
            hy, hm, hd = hebrew.from_gregorian(d.year, d.month, d.day)
            want = 13 if hebrew.leap(hy) else 12
            assert (hm, hd) == (want, 14), (code, d, hy, hm, hd)
        return
    if code in HEBREW_CHECK:
        for d in ds:
            _, hm, hd = hebrew.from_gregorian(d.year, d.month, d.day)
            assert (hm, hd) == HEBREW_CHECK[code], (code, d, hm, hd)


def b36(n: int) -> str:
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    s = ""
    for _ in range(3):
        s = digits[n % 36] + s
        n //= 36
    assert n == 0
    return s


def main() -> None:
    lines = [
        "// Generated by training/gen/lunar/make_tables.py from the `holidays` package (0.83). Do not edit.",
        "// Each value lists every date of the holiday in 2000-2100 that the source covers, in order, as days since",
        "// 2000-01-01, three base-36 digits each. Coverage: Chinese and Hebrew 2000-2100, Islamic (Umm al-Qura) 2000-2077,",
        "// Diwali and Holi (India) 2001-2035.",
        "export const LUNAR_TABLE: Record<string, string> = {",
    ]
    for code, table in SOURCES.items():
        ds = dates(table)
        check_hebrew(code, ds)
        enc = "".join(b36((d - EPOCH).days) for d in ds)
        lines.append(f'  {code}: "{enc}",')
        print(f"{code}: {len(ds)} dates, {ds[0]} to {ds[-1]}")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
